function getActiveBranch(state: MockStoreState): Branch {
  return state.branches.find((b) => b.is_active) ?? state.branches[0]!;
}

function buildMockGraphData(query: GraphQuery): GraphData {
  const state = ensureMockState();
  const activeBranch = getActiveBranch(state);
  const targetBranchId = query.branch_id ?? activeBranch.id;
  const branchObj = state.branches.find((b) => b.id === targetBranchId) ?? activeBranch;

  const allNodes: GraphNode[] = [];
  for (const m of state.memories.values()) {
    if (m.branch_id !== targetBranchId) continue;
    if (!query.include_archived && m.status === "archived") continue;
    if (!query.include_superseded && m.status === "superseded") continue;
    allNodes.push(memoryToGraphNode(m));
  }

  const limitedNodes = query.limit !== null ? allNodes.slice(0, query.limit) : allNodes;
  const visibleIds = new Set(limitedNodes.map((n) => n.id));
  const minWeight = query.min_edge_weight ?? 0;
  const filteredEdges = state.edges.filter(
    (e) =>
      visibleIds.has(e.source_id) &&
      visibleIds.has(e.target_id) &&
      e.weight >= minWeight,
  );

  const projects: ProjectStats[] = MOCK_PROJECTS_SEED.map(({ project }) => {
    const projectNodes = limitedNodes.filter((n) => n.project_id === project.id);
    return {
      project,
      vector_count: projectNodes.length,
      total_tokens: projectNodes.reduce((sum, n) => sum + n.chunk_tokens, 0),
      reusable_count: projectNodes.filter((n) => n.is_reusable).length,
    };
  });

  return {
    nodes: limitedNodes,
    edges: filteredEdges,
    projects,
    branch: branchObj,
  };
}

