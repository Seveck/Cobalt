function buildMockHardwareProfile(): HardwareProfile {
  const logicalCores =
    typeof navigator !== "undefined" && navigator.hardwareConcurrency > 0
      ? navigator.hardwareConcurrency
      : 8;

  const navWithMemory =
    typeof navigator !== "undefined"
      ? (navigator as Navigator & { deviceMemory?: number })
      : undefined;
  const detectedGb =
    navWithMemory && typeof navWithMemory.deviceMemory === "number" && navWithMemory.deviceMemory > 0
      ? navWithMemory.deviceMemory
      : 16;

  const totalRamBytes = Math.round(detectedGb * 1024 * 1024 * 1024);
  const availableRamBytes = Math.round(totalRamBytes * 0.62);

  let tier: HardwareTier = "balanced";
  let reasonKey = "onboarding.reason.balanced_ram";
  if (detectedGb <= 8 || logicalCores <= 4) {
    tier = "eco";
    reasonKey = "onboarding.reason.low_ram";
  } else if (detectedGb >= 32 && logicalCores >= 12) {
    tier = "ultra";
    reasonKey = "onboarding.reason.high_ram_gpu";
  }

  const engine = DEFAULT_ENGINE_BY_TIER[tier];
  const modelId = DEFAULT_MODEL_BY_TIER[tier];
  const modelSpec = MOCK_EMBEDDING_MODELS.find((m) => m.id === modelId);
  const recommendedAlreadyInstalled =
    mockEngineStatus.engine === engine &&
    mockEngineStatus.model_id === modelId &&
    (mockEngineStatus.engine_state === "installed" ||
      mockEngineStatus.engine_state === "running" ||
      mockEngineStatus.engine_state === "stopped") &&
    (mockEngineStatus.model_state === "installed" ||
      mockEngineStatus.model_state === "running" ||
      mockEngineStatus.model_state === "stopped");
  const downloadBytes = recommendedAlreadyInstalled
    ? 0
    : (modelSpec?.size_bytes ?? 124_151_398) + ENGINE_SIDECAR_BYTES[engine];

  return {
    os: "linux",
    os_version: "Browser Preview",
    arch: "x86_64",
    total_ram_bytes: totalRamBytes,
    available_ram_bytes: availableRamBytes,
    cpu_brand: "Simulated Desktop CPU",
    physical_cores: Math.max(2, Math.floor(logicalCores / 2)),
    logical_cores: logicalCores,
    gpus: [
      {
        name: "Integrated WebGL Adapter",
        vendor_id: 0x8086,
        device_type: "integrated_gpu",
        backend: "browser_webgpu",
      },
    ],
    recommendation: {
      tier,
      engine,
      model_id: modelId,
      download_bytes: downloadBytes,
      reason_key: reasonKey,
    },
  };
}

