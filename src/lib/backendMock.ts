/** Typed mock listener mirroring `src/lib/ipc.ts` `on()`. */
export async function onBackendMock<E extends EventName>(
  event: E,
  handler: (payload: EventPayloadMap[E]) => void,
): Promise<UnlistenFn> {
  mockListeners[event].add(handler);
  return () => {
    mockListeners[event].delete(handler);
  };
}

/** Typed mock command dispatcher mirroring `src/lib/ipc.ts` `call()`. */
export async function callBackendMock<C extends IpcCommand>(
  command: C,
  ...rest: ArgsOf<C> extends void ? [] : [args: ArgsOf<C>]
): Promise<ResultOf<C>> {
  const args = rest[0];

  switch (command) {
    case "app_info": {
      const info: AppInfo = {
        name: "Cobalt",
        version: "0.1.0",
        os: "browser",
        arch: "wasm",
        contract_version: CONTRACT_VERSION,
        schema_version: SCHEMA_VERSION,
        data_dir: "~/.cobalt (mock)",
      };
      return info as ResultOf<C>;
    }
    case "get_hardware_profile": {
      return buildMockHardwareProfile() as ResultOf<C>;
    }
    case "get_settings": {
      return { ...mockSettings } as ResultOf<C>;
    }
    case "update_settings": {
      const next = args as AppSettings;
      mockSettings = { ...next };
      persistMockSettings(mockSettings);
      return { ...mockSettings } as ResultOf<C>;
    }
    case "list_embedding_models": {
      return [...MOCK_EMBEDDING_MODELS] as ResultOf<C>;
    }
    case "install_engine": {
      const status = await runSimulatedInstallMock(args as EngineInstallRequest);
      return status as ResultOf<C>;
    }
    case "cancel_download": {
      if (activeMockDownload) {
        activeMockDownload.cancelled = true;
      }
      return undefined as ResultOf<C>;
    }
    case "get_engine_status": {
      return { ...mockEngineStatus } as ResultOf<C>;
    }
    case "get_graph": {
      const query = args as GraphQuery;
      const base = buildMockGraphData();
      const filteredNodes = base.nodes.filter((n) => {
        if (!query.include_archived && n.status === "archived") return false;
        if (!query.include_superseded && n.status === "superseded") return false;
        return true;
      });
      const limitedNodes =
        query.limit !== null ? filteredNodes.slice(0, query.limit) : filteredNodes;
      const visibleIds = new Set(limitedNodes.map((n) => n.id));
      const minWeight = query.min_edge_weight ?? 0;
      const filteredEdges = base.edges.filter(
        (e) =>
          visibleIds.has(e.source_id) &&
          visibleIds.has(e.target_id) &&
          e.weight >= minWeight,
      );
      const data: GraphData = {
        nodes: limitedNodes,
        edges: filteredEdges,
        projects: base.projects,
        branch: base.branch,
      };
      return data as ResultOf<C>;
    }
    case "list_branches": {
      const branches: Branch[] = [MOCK_MAIN_BRANCH];
      return branches as ResultOf<C>;
    }
    case "list_library": {
      return buildMockLibrary(args as LibraryFilter) as ResultOf<C>;
    }
    case "get_telemetry_summary": {
      return buildMockTelemetrySummary() as ResultOf<C>;
    }
    case "list_connectors": {
      return buildMockConnectors() as ResultOf<C>;
    }
    case "list_installed_themes": {
      return buildMockInstalledThemes() as ResultOf<C>;
    }
    case "get_theme_manifest": {
      return MINIMAL_THEME_MANIFEST as ResultOf<C>;
    }
    case "get_read_only": {
      return mockSettings.read_only as ResultOf<C>;
    }
    case "set_read_only": {
      const { read_only } = args as { read_only: boolean };
      mockSettings = { ...mockSettings, read_only };
      persistMockSettings(mockSettings);
      emitMockEvent("cobalt://read-only-changed", { read_only });
      return read_only as ResultOf<C>;
    }
    case "get_daemon_status": {
      const status: DaemonStatus = {
        running: false,
        started_at: new Date().toISOString(),
        read_only: mockSettings.read_only,
        http_port: mockSettings.mcp.http_enabled ? mockSettings.mcp.http_port : null,
        queued_writes: 0,
        clients: [],
      };
      return status as ResultOf<C>;
    }
    default: {
      throw new IpcError(command, {
        kind: "unsupported",
        message: `Command "${command}" is not implemented in Phase 1 mock adapter.`,
      });
    }
  }
}
