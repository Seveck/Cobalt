function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => {
    setTimeout(resolve, ms);
  });
}

async function runSimulatedInstallMock(req: EngineInstallRequest): Promise<EngineStatus> {
  const model = MOCK_EMBEDDING_MODELS.find((m) => m.id === req.model_id);
  const totalBytes = (model?.size_bytes ?? 124_151_398) + ENGINE_SIDECAR_BYTES[req.engine];
  const artifactId = `${req.engine}:${req.model_id}`;

  const token: ActiveMockDownload = { artifactId, cancelled: false };
  activeMockDownload = token;

  mockEngineStatus = {
    ...mockEngineStatus,
    engine: req.engine,
    model_id: req.model_id,
    engine_state: "downloading",
    model_state: "downloading",
    last_error: null,
  };

  const emit = (
    phase: DownloadProgress["phase"],
    downloadedBytes: number,
    message: string | null = null,
  ) => {
    emitMockEvent("cobalt://download-progress", {
      artifact_id: artifactId,
      phase,
      downloaded_bytes: downloadedBytes,
      total_bytes: totalBytes,
      attempt: 1,
      message,
    });
  };

  emit("queued", 0);
  await sleep(160);

  const steps = 10;
  for (let step = 1; step <= steps; step += 1) {
    if (token.cancelled) {
      activeMockDownload = null;
      emit("cancelled", Math.round((totalBytes * (step - 1)) / steps), "Cancelled by user");
      mockEngineStatus = {
        ...mockEngineStatus,
        engine_state: "not_installed",
        model_state: "not_installed",
      };
      throw new IpcError("install_engine", {
        kind: "cancelled",
        message: "Download cancelled by user",
      });
    }
    const downloaded = Math.round((totalBytes * step) / steps);
    emit("downloading", downloaded);
    await sleep(180);
  }

  if (token.cancelled) {
    activeMockDownload = null;
    emit("cancelled", totalBytes, "Cancelled by user");
    throw new IpcError("install_engine", {
      kind: "cancelled",
      message: "Download cancelled by user",
    });
  }

  emit("verifying", totalBytes, "SHA-256");
  await sleep(220);

  emit("extracting", totalBytes);
  await sleep(180);

  emit("completed", totalBytes);
  activeMockDownload = null;

  mockEngineStatus = {
    engine: req.engine,
    engine_state: "running",
    model_id: req.model_id,
    model_state: "installed",
    dimensions: model?.dimensions ?? 384,
    vector_count: MOCK_GRAPH_NODE_COUNT,
    installed_bytes: totalBytes,
    sidecar_endpoint: req.engine === "qdrant_sidecar" ? "http://127.0.0.1:6333" : null,
    last_error: null,
  };

  return mockEngineStatus;
}

function buildMockLibrary(filter: LibraryFilter): ReusableAsset[] {
  const graph = buildMockGraphData();
  const projectMap = new Map(graph.projects.map((p) => [p.project.id, p.project]));
  const query = filter.query?.trim().toLowerCase() ?? "";

  const assets: ReusableAsset[] = graph.nodes
    .filter((node) => node.is_reusable)
    .map((node): ReusableAsset => {
      const proj = node.project_id ? projectMap.get(node.project_id) : undefined;
      return {
        memory_id: node.id,
        summary: node.preview,
        source_type: node.source_type,
        origin_project_id: node.project_id,
        origin_project_name: proj?.name ?? null,
        origin_project_color: proj?.color_hex ?? null,
        source_doc_id: node.source_doc_id,
        file_path: proj ? `${proj.root_path ?? "/workspace"}/snippets/${node.id.slice(-6)}.${node.source_type}` : null,
        availability: "available",
        snippet: `// Reusable ${node.source_type} fragment (${node.chunk_tokens} tokens)`,
        reuse_count: node.reuse_count,
        output_tokens_saved: node.reuse_count * node.chunk_tokens,
        similarity_score: node.confidence,
        status: node.status,
      };
    })
    .filter((asset) => {
      if (query && !asset.summary.toLowerCase().includes(query)) return false;
      if (filter.source_types.length > 0 && !filter.source_types.includes(asset.source_type)) {
        return false;
      }
      if (
        filter.project_ids.length > 0 &&
        (!asset.origin_project_id || !filter.project_ids.includes(asset.origin_project_id))
      ) {
        return false;
      }
      return true;
    });

  const offset = filter.offset ?? 0;
  const limit = filter.limit ?? assets.length;
  return assets.slice(offset, offset + limit);
}

