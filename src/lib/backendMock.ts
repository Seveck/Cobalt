async function runSimulatedInstallMock(req: EngineInstallRequest): Promise<EngineStatus> {
  const model = MOCK_EMBEDDING_MODELS.find((m) => m.id === req.model_id);
  const totalBytes = (model?.size_bytes ?? 124_151_398) + ENGINE_SIDECAR_BYTES[req.engine];
  const artifactId = `${req.engine}:${req.model_id}`;

  const token: ActiveMockDownload = { artifactId, cancelled: false };
  activeMockDownload = token;

  mockEngineStatus = {
    ...mockEngineStatus,
    engine: req.engine,
    model_id: req.model_id,
    engine_state: "downloading",
    model_state: "downloading",
    last_error: null,
  };

  const emit = (
    phase: DownloadProgress["phase"],
    downloadedBytes: number,
    message: string | null = null,
  ) => {
    emitMockEvent("cobalt://download-progress", {
      artifact_id: artifactId,
      phase,
      downloaded_bytes: downloadedBytes,
      total_bytes: totalBytes,
      attempt: 1,
      message,
    });
  };

  emit("queued", 0);
  await sleep(160);

  const steps = 10;
  for (let step = 1; step <= steps; step += 1) {
    if (token.cancelled) {
      activeMockDownload = null;
      emit("cancelled", Math.round((totalBytes * (step - 1)) / steps), "Cancelled by user");
      mockEngineStatus = {
        ...mockEngineStatus,
        engine_state: "not_installed",
        model_state: "not_installed",
      };
      throw new IpcError("install_engine", {
        kind: "cancelled",
        message: "Download cancelled by user",
      });
    }
    const downloaded = Math.round((totalBytes * step) / steps);
    emit("downloading", downloaded);
    await sleep(180);
  }

  if (token.cancelled) {
    activeMockDownload = null;
    emit("cancelled", totalBytes, "Cancelled by user");
    throw new IpcError("install_engine", {
      kind: "cancelled",
      message: "Download cancelled by user",
    });
  }

  emit("verifying", totalBytes, "SHA-256");
  await sleep(220);

  emit("extracting", totalBytes);
  await sleep(180);

  emit("completed", totalBytes);
  activeMockDownload = null;

  mockEngineStatus = {
    engine: req.engine,
    engine_state: "running",
    model_id: req.model_id,
    model_state: "installed",
    dimensions: model?.dimensions ?? 384,
    vector_count: ensureMockState().memories.size,
    installed_bytes: totalBytes,
    sidecar_endpoint: req.engine === "qdrant_sidecar" ? "http://127.0.0.1:6333" : null,
    last_error: null,
  };

  return mockEngineStatus;
}

