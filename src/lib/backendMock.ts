let cachedMockGraph: GraphData | null = null;

function buildMockGraphData(): GraphData {
  if (cachedMockGraph) return cachedMockGraph;

  const rng = createSeededRng(0xc0ba17);
  const nodes: GraphNode[] = [];
  const edges: MemoryEdge[] = [];

  for (let i = 0; i < MOCK_GRAPH_NODE_COUNT; i += 1) {
    const isGlobal = i >= 270;
    const projectSeed = isGlobal ? null : (MOCK_PROJECTS_SEED[i % 3] ?? null);
    const id = deterministicUuid("0193a000", i + 1);

    const category: MemoryCategory =
      MEMORY_CATEGORIES[Math.floor(rng() * MEMORY_CATEGORIES.length)] ?? "note";
    const sourceTypes: readonly SourceType[] = projectSeed
      ? projectSeed.sourceTypes
      : ["md", "note", "bash"];
    const sourceType: SourceType =
      sourceTypes[Math.floor(rng() * sourceTypes.length)] ?? "note";

    const isCorePin = i < 12 || (isGlobal && i < 274);
    const isReusable = !isCorePin && rng() < 0.14;
    const isSuperseded = !isCorePin && rng() < 0.04;
    const isArchived = !isCorePin && !isSuperseded && rng() < 0.03;
    const status = isSuperseded ? "superseded" : isArchived ? "archived" : "active";

    // Spiral + cluster offset kept comfortably inside sphere radius 95 (<= 100)
    const center: Vec3 = projectSeed ? projectSeed.clusterCenter : [0, -28, 0];
    const angle = i * 0.42 + rng() * 0.5;
    const radial = 6 + Math.pow(rng(), 0.65) * 32;
    const elevation = (rng() - 0.5) * 26;
    let x = center[0] + Math.cos(angle) * radial;
    let y = center[1] + elevation;
    let z = center[2] + Math.sin(angle) * radial;
    const norm = Math.hypot(x, y, z);
    if (norm > 94) {
      const scale = 94 / norm;
      x *= scale;
      y *= scale;
      z *= scale;
    }

    const topicPool = projectSeed ? projectSeed.topics : GLOBAL_TOPICS;
    const baseTopic = topicPool[i % topicPool.length] ?? "Stored memory fragment";
    const preview = `${baseTopic} (#${i + 1})`;

    const hitCount = isCorePin
      ? 14 + Math.floor(rng() * 35)
      : Math.floor(Math.pow(rng(), 2) * 24);
    const reuseCount = isReusable ? 2 + Math.floor(rng() * 14) : 0;
    const chunkTokens = 45 + Math.floor(rng() * 340);
    const updatedAt = new Date(MOCK_CREATED_BASE_MS + i * 7_200_000).toISOString();

    nodes.push({
      id,
      branch_id: MAIN_BRANCH_ID,
      project_id: projectSeed ? projectSeed.project.id : null,
      source_doc_id: projectSeed ? deterministicUuid("0193d000", (i % 45) + 1) : null,
      source_type: sourceType,
      category,
      status,
      confidence: Number((0.68 + rng() * 0.32).toFixed(2)),
      is_core_pin: isCorePin,
      is_reusable: isReusable,
      is_encrypted: false,
      reuse_count: reuseCount,
      hit_count: hitCount,
      relevance_score: isCorePin ? 1.0 : Number((0.35 + rng() * 0.65).toFixed(2)),
      chunk_tokens: chunkTokens,
      superseded_by: null,
      position: [Number(x.toFixed(2)), Number(y.toFixed(2)), Number(z.toFixed(2))],
      preview,
      updated_at: updatedAt,
    });
  }

  // Deterministic edges within & across projects
  const edgeKeys = new Set<string>();
  const addEdge = (sourceIdx: number, targetIdx: number, edgeType: EdgeType, weight: number) => {
    if (sourceIdx === targetIdx) return;
    const source = nodes[sourceIdx];
    const target = nodes[targetIdx];
    if (!source || !target) return;
    const key = `${source.id}:${target.id}:${edgeType}`;
    if (edgeKeys.has(key)) return;
    edgeKeys.add(key);
    edges.push({
      source_id: source.id,
      target_id: target.id,
      edge_type: edgeType,
      weight: Number(weight.toFixed(2)),
    });
  };

  for (let i = 0; i < nodes.length; i += 1) {
    const sameProjectNeighbor = i + 3 < 270 && i < 270 ? i + 3 : (i + 1) % nodes.length;
    addEdge(i, sameProjectNeighbor, "same_project", 0.55 + rng() * 0.35);

    if (rng() < 0.55) {
      const semanticTarget = Math.floor(rng() * nodes.length);
      addEdge(i, semanticTarget, "semantic", 0.72 + rng() * 0.26);
    }
  }

  const projects: ProjectStats[] = MOCK_PROJECTS_SEED.map(({ project }) => {
    const projectNodes = nodes.filter((n) => n.project_id === project.id);
    return {
      project,
      vector_count: projectNodes.length,
      total_tokens: projectNodes.reduce((sum, n) => sum + n.chunk_tokens, 0),
      reusable_count: projectNodes.filter((n) => n.is_reusable).length,
    };
  });

  cachedMockGraph = {
    nodes,
    edges,
    projects,
    branch: MOCK_MAIN_BRANCH,
  };
  return cachedMockGraph;
}

